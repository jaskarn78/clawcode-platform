import { mkdir, writeFile, readdir, readFile, rename } from "node:fs/promises";
import { join } from "node:path";
import { nanoid } from "nanoid";
import type {
  InboxMessage,
  InboxMessageKind,
  MessagePriority,
  ResolvedEnvelope,
} from "./types.js";
import { logger } from "../shared/logger.js";

/**
 * Quick 260520-r70 — single source of truth for inbox-message kind
 * default-resolution. An ABSENT or otherwise-unrecognized `kind` resolves
 * to "message" so legacy on-disk inbox JSON (written before the `kind`
 * field existed) is always treated as a genuine message. Used by both the
 * shared ack-emitter and the inbox consumers so an absent kind never
 * rejects a file.
 *
 * @param msg - Anything carrying an optional `kind`
 * @returns The resolved kind ("message" when absent/unknown)
 */
export function resolveKind(msg: { kind?: InboxMessageKind }): InboxMessageKind {
  return msg.kind === "ack" ? "ack" : "message";
}

/**
 * Create a new InboxMessage with a generated id and current timestamp.
 *
 * @param from - Sender agent name
 * @param to - Recipient agent name
 * @param content - Message content
 * @param priority - Message priority (defaults to "normal")
 * @param kind - Message-role discriminator (defaults to "message").
 *   Quick 260520-r70 — pass "ack" for acknowledgment messages so a
 *   future consume of the ack is a no-op (loop prevention).
 * @returns A fully populated InboxMessage
 */
export function createMessage(
  from: string,
  to: string,
  content: string,
  priority: MessagePriority = "normal",
  kind: InboxMessageKind = "message",
  envelope: Partial<
    Pick<
      InboxMessage,
      "conversationId" | "causationId" | "deliveryId" | "hops" | "autoSubmitted"
    >
  > = {},
): InboxMessage {
  const id = nanoid();
  return {
    id,
    from,
    to,
    content,
    timestamp: Date.now(),
    priority,
    kind,
    // Phase 999.117 WS-1 — envelope. A caller that passes nothing starts a
    // fresh single-hop conversation, which is the correct reading of "an
    // agent decided to message another agent out of the blue". A caller
    // continuing an exchange threads `conversationId` + `hops` through, and
    // the loop governor can then see the depth.
    conversationId: envelope.conversationId ?? id,
    causationId: envelope.causationId,
    deliveryId: envelope.deliveryId ?? id,
    hops: envelope.hops ?? 1,
    // Acks are machine-generated by definition; an explicit flag still wins
    // so a caller can mark any other automated traffic (RFC 3834).
    autoSubmitted: envelope.autoSubmitted ?? kind === "ack",
  };
}

/**
 * Phase 999.117 WS-1 — resolve an inbox message's envelope, supplying every
 * default. This is the ONLY place envelope defaults live; read the result
 * rather than the raw optional fields, so a legacy message (written before
 * the envelope existed) and a fresh one are handled identically.
 *
 * A legacy message resolves to a fresh single-hop conversation keyed by its
 * own id — the safe reading, since nothing is known about what preceded it.
 */
export function resolveEnvelope(msg: InboxMessage): ResolvedEnvelope {
  return {
    conversationId: msg.conversationId ?? msg.id,
    causationId: msg.causationId,
    deliveryId: msg.deliveryId ?? msg.id,
    hops: typeof msg.hops === "number" && msg.hops > 0 ? msg.hops : 1,
    autoSubmitted: msg.autoSubmitted ?? resolveKind(msg) === "ack",
    kind: resolveKind(msg),
  };
}

/**
 * Write a message to an agent's inbox directory as a JSON file.
 * Uses atomic write pattern: write to .tmp then rename.
 * Creates the inbox directory if it doesn't exist.
 *
 * @param inboxDir - Path to the agent's inbox directory
 * @param message - The message to write
 */
export async function writeMessage(
  inboxDir: string,
  message: InboxMessage,
): Promise<void> {
  await mkdir(inboxDir, { recursive: true });

  const filename = `${message.timestamp}-${message.from}-${nanoid(6)}.json`;
  const filePath = join(inboxDir, filename);
  const tmpPath = `${filePath}.tmp`;

  const data = JSON.stringify(message, null, 2);
  await writeFile(tmpPath, data, "utf-8");
  await rename(tmpPath, filePath);
}

/**
 * Read all messages from an agent's inbox directory.
 * Returns messages sorted by timestamp ascending.
 * Skips malformed files with a warning log.
 * Returns empty array if the directory doesn't exist.
 *
 * @param inboxDir - Path to the agent's inbox directory
 * @returns Array of parsed InboxMessages sorted by timestamp
 */
export async function readMessages(
  inboxDir: string,
): Promise<readonly InboxMessage[]> {
  let entries: string[];
  try {
    entries = await readdir(inboxDir);
  } catch {
    return [];
  }

  const jsonFiles = entries.filter((f) => f.endsWith(".json"));
  const messages: InboxMessage[] = [];

  for (const file of jsonFiles) {
    try {
      const raw = await readFile(join(inboxDir, file), "utf-8");
      const parsed = JSON.parse(raw) as InboxMessage;

      if (!parsed.id || !parsed.from || !parsed.to || !parsed.content || !parsed.timestamp) {
        logger.warn({ file }, "skipping malformed inbox message file");
        continue;
      }

      messages.push(parsed);
    } catch {
      logger.warn({ file }, "failed to parse inbox message file");
    }
  }

  return messages.sort((a, b) => a.timestamp - b.timestamp);
}

/**
 * Mark a message as processed by moving it to the processed subdirectory.
 * Matches by scanning file contents for the given message id.
 * No-op if the message file is not found (idempotent).
 *
 * @param inboxDir - Path to the agent's inbox directory
 * @param messageId - The id of the message to mark as processed
 */
export async function markProcessed(
  inboxDir: string,
  messageId: string,
): Promise<void> {
  let entries: string[];
  try {
    entries = await readdir(inboxDir);
  } catch {
    return;
  }

  const jsonFiles = entries.filter((f) => f.endsWith(".json"));

  for (const file of jsonFiles) {
    try {
      const raw = await readFile(join(inboxDir, file), "utf-8");
      const parsed = JSON.parse(raw) as InboxMessage;

      if (parsed.id === messageId) {
        const processedDir = join(inboxDir, "processed");
        await mkdir(processedDir, { recursive: true });
        await rename(join(inboxDir, file), join(processedDir, file));
        return;
      }
    } catch {
      // Skip unreadable files
    }
  }
}

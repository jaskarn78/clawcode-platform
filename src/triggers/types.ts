/**
 * Phase 60 Plan 01 — trigger engine data types.
 *
 * Provides the TriggerEvent Zod schema (validated at ingress), the
 * TriggerSource interface (implemented by Phase 61 source adapters),
 * and TriggerEngineOptions (constructor shape for the engine).
 *
 * These are pure-data definitions with zero runtime side effects.
 * Plans 60-02 and 60-03 depend on every export here — do NOT rename
 * without updating downstream plan references.
 */

import { z } from "zod/v4";

// ---------------------------------------------------------------------------
// TriggerEvent — the universal shape for every trigger source emission.
// ---------------------------------------------------------------------------

export const TriggerEventSchema = z.object({
  sourceId: z.string().min(1),
  idempotencyKey: z.string().min(1),
  targetAgent: z.string().min(1),
  payload: z.unknown(),
  timestamp: z.number().int().min(0),
  /** Phase 62 — optional source kind for policy DSL matching. */
  sourceKind: z.string().optional(),
});

export type TriggerEvent = z.infer<typeof TriggerEventSchema>;

// ---------------------------------------------------------------------------
// TriggerSource — plugin interface for Phase 61 source adapters.
// ---------------------------------------------------------------------------

/**
 * Every trigger source (scheduler, webhook, MySQL poller, inbox watcher,
 * calendar) implements this interface. The engine is source-agnostic.
 *
 * `poll` is optional — only needed for sources that support watermark-based
 * replay on daemon restart (TRIG-06).
 */
export type TriggerSource = {
  readonly sourceId: string;
  start(): void;
  stop(): void;
  /** Called on daemon restart to replay missed events since watermark. */
  poll?(since: string | null): Promise<readonly TriggerEvent[]>;
};

// ---------------------------------------------------------------------------
// TriggerDeliveryFn — Phase 100 follow-up.
// ---------------------------------------------------------------------------

/**
 * Phase 100 follow-up — delivery callback for trigger-fired output.
 *
 * Bug fixed (2026-04-27): `TriggerEngine.ingest()` previously called
 * `await turnDispatcher.dispatch(...)` and discarded the returned response
 * string. Scheduled cron output (e.g. fin-client's 15-min status check)
 * was generated by the agent but never reached Discord — the held content
 * stayed in the agent's conversation history and got dragged into the next
 * user-msg-driven reply, producing wrong-slot attribution.
 *
 * When `deliveryFn` is provided to TriggerEngine, the engine invokes it
 * after every successful dispatch with the response text, so the daemon can
 * route it to the agent's bound delivery surface (typically the Discord
 * channel, via the agent's webhook or the bot-direct fallback).
 *
 * Failures are caught + warn-logged + swallowed by the engine so a delivery
 * hiccup does not block subsequent triggers and the watermark still advances
 * (otherwise we'd reprocess the tick on the next replay and double-dispatch).
 */
/**
 * 999.178 R1 — optional delivery context. Carries the trigger `sourceId` (or a
 * caller-supplied label) so a failed scheduled post can be dead-lettered to the
 * operator naming WHICH schedule dropped output, instead of "schedule: unknown".
 * Optional and additive: a 2-arg deliveryFn still satisfies the type.
 */
export type TriggerDeliveryContext = {
  readonly label?: string;
};

export type TriggerDeliveryFn = (
  targetAgent: string,
  response: string,
  context?: TriggerDeliveryContext,
) => Promise<void>;

// ---------------------------------------------------------------------------
// TriggerEngineOptions — constructor shape for TriggerEngine (Plan 60-02).
// ---------------------------------------------------------------------------

export type TriggerEngineOptions = Readonly<{
  turnDispatcher: import("../manager/turn-dispatcher.js").TurnDispatcher;
  taskStore: import("../tasks/store.js").TaskStore;
  log: import("pino").Logger;
  config: Readonly<{
    replayMaxAgeMs: number;
    dedupLruSize: number;
    defaultDebounceMs: number;
  }>;
  /**
   * Optional delivery callback. When provided, TriggerEngine calls it
   * after every successful dispatch with the response text. Without it,
   * dispatched responses are discarded (back-compat with pre-Phase-100
   * behavior — existing daemons / tests / embedded uses keep working).
   */
  deliveryFn?: TriggerDeliveryFn;
}>;

// ---------------------------------------------------------------------------
// Default constants — exported for use by config schema and tests.
